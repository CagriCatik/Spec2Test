"""Review use cases: revisions, editing, clarification and approval.

Rules enforced here:

* every saved change creates a new revision and keeps the previous one;
* an approval never carries over to a new revision;
* approval re-runs the deterministic validation and is refused while a
  blocking finding or an unresolved question remains;
* a question is cleared with an answer, never deleted;
* changed sources mark the affected drafts for a fresh review.

No Qt, no HTTP, no file access.
"""
from __future__ import annotations

from dataclasses import dataclass, replace
from datetime import datetime, timezone
from typing import Iterable, Sequence

from ..domain.models import (
    AcceptedFinding,
    GenerationRun,
    OpenQuestion,
    Project,
    QuestionOrigin,
    Requirement,
    ReviewAction,
    ReviewEvent,
    ReviewStatus,
    SourceDocument,
    TestCase,
    TestStep,
)
from ..domain.models import Severity
from ..domain.validation import ValidationReport, may_approve, validate_test_case

DEFAULT_REVIEWER = "tester"


class ReviewError(RuntimeError):
    """A review action that must not be carried out."""


class ApprovalBlocked(ReviewError):
    """Approval was refused; ``report`` says why."""

    def __init__(self, message: str, report: ValidationReport) -> None:
        super().__init__(message)
        self.report = report


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


@dataclass
class CaseEdit:
    """The fields a reviewer may change. ``None`` means "leave unchanged"."""

    title: str | None = None
    objective: str | None = None
    preconditions: tuple[TestStep, ...] | None = None
    steps: tuple[TestStep, ...] | None = None
    postconditions: tuple[TestStep, ...] | None = None
    requirement_ids: tuple[str, ...] | None = None

    def changes(self) -> dict:
        return {
            name: value
            for name, value in vars(self).items()
            if value is not None
        }


# ----------------------------------------------------------------- project ---
def project_from_run(
    run: GenerationRun,
    requirements: Sequence[Requirement],
    documents: Sequence[SourceDocument],
    *,
    name: str,
    project_id: str | None = None,
) -> Project:
    """Build a project from a finished run, ready to be saved and reopened."""
    project = Project(
        project_id=project_id or f"prj-{run.run_id}",
        name=name,
        created_at=_now(),
        documents=list(documents),
        requirements=list(requirements),
        test_cases=list(run.test_cases),
        runs=[run],
        open_questions=list(run.open_questions),
    )
    for case in project.test_cases:
        project.history.append(
            ReviewEvent(
                action=ReviewAction.CREATED,
                case_id=case.case_id,
                revision=case.revision,
                at=project.created_at,
                status_after=case.review_status,
                note=f"generated by run {run.run_id}",
            )
        )
    return project


def add_run(project: Project, run: GenerationRun, requirements: Sequence[Requirement]) -> None:
    """Add the result of a further run without touching existing drafts."""
    known = {r.requirement_id for r in project.requirements}
    project.requirements.extend(r for r in requirements if r.requirement_id not in known)
    project.runs.append(run)
    project.open_questions.extend(run.open_questions)
    for case in run.test_cases:
        project.test_cases.append(case)
        project.history.append(
            ReviewEvent(
                action=ReviewAction.CREATED,
                case_id=case.case_id,
                revision=case.revision,
                at=_now(),
                status_after=case.review_status,
                note=f"generated by run {run.run_id}",
            )
        )


# -------------------------------------------------------------------- edit ---
def edit_case(
    project: Project,
    case_id: str,
    edit: CaseEdit,
    *,
    by: str = DEFAULT_REVIEWER,
    note: str | None = None,
    categories: Sequence[str] = (),
) -> TestCase:
    """Save an edit as a new revision. An existing approval is dropped."""
    case = _require_case(project, case_id)
    changes = edit.changes()
    if not changes:
        raise ReviewError("nothing to change")

    previous_status = case.review_status
    updated = case.next_revision(**changes)
    updated = replace(updated, needs_recheck=False, review_note=note)
    project.replace_case(updated)
    project.history.append(
        ReviewEvent(
            action=ReviewAction.EDITED,
            case_id=case_id,
            revision=updated.revision,
            at=_now(),
            by=by,
            note=note or f"changed: {', '.join(sorted(changes))}",
            status_before=previous_status,
            status_after=updated.review_status,
            categories=tuple(categories),
        )
    )
    return updated


def revisions_of(project: Project, case_id: str) -> list[TestCase]:
    """Every revision, oldest first, with the current one last."""
    history = list(project.revisions.get(case_id, []))
    current = project.case(case_id)
    if current is not None:
        history.append(current)
    return history


# --------------------------------------------------------------- questions ---
def resolve_question(
    project: Project,
    case_id: str,
    question_id: str,
    answer: str,
    *,
    by: str = DEFAULT_REVIEWER,
) -> TestCase:
    """Mark a question as cleared. The question and its answer are kept."""
    case = _require_case(project, case_id)
    if not any(q.question_id == question_id for q in case.open_questions):
        raise ReviewError(f"{case_id} has no question {question_id!r}")

    at = _now()
    questions = tuple(
        q.resolve(answer, by=by, at=at) if q.question_id == question_id else q
        for q in case.open_questions
    )
    # clearing a question is not a content change: the revision stays
    updated = replace(case, open_questions=questions)
    project.test_cases[project.test_cases.index(case)] = updated
    project.history.append(
        ReviewEvent(
            action=ReviewAction.QUESTION_RESOLVED,
            case_id=case_id,
            revision=case.revision,
            at=at,
            by=by,
            note=f"{question_id}: {answer.strip()}",
        )
    )
    return updated


def add_question(
    project: Project,
    case_id: str,
    question: str,
    *,
    by: str = DEFAULT_REVIEWER,
    suggestion: str | None = None,
) -> TestCase:
    """A reviewer's own question. It blocks approval like any other."""
    case = _require_case(project, case_id)
    new_question = OpenQuestion(
        question_id=f"{case_id}-R{len(case.open_questions) + 1:02d}",
        question=question.strip(),
        requirement_ids=case.requirement_ids,
        origin=QuestionOrigin.REVIEWER,
        suggestion=suggestion,
    )
    updated = replace(case, open_questions=(*case.open_questions, new_question))
    project.test_cases[project.test_cases.index(case)] = updated
    project.history.append(
        ReviewEvent(
            action=ReviewAction.CLARIFICATION_REQUESTED,
            case_id=case_id,
            revision=case.revision,
            at=_now(),
            by=by,
            note=new_question.question,
        )
    )
    return updated


def accept_finding(
    project: Project,
    case_id: str,
    code: str,
    path: str,
    justification: str,
    *,
    by: str = DEFAULT_REVIEWER,
) -> TestCase:
    """Accept a clarification finding with a stated reason.

    Only clarifications can be accepted. An error - an unknown requirement, a
    missing step, an invalid type - always blocks, because no justification
    makes a structurally broken draft usable.
    """
    case = _require_case(project, case_id)
    if not justification.strip():
        raise ReviewError("accepting a finding needs a reason")

    report = validate_test_case(case, project.requirements)
    match = next(
        (i for i in report.issues if i.code == code and i.path == path), None
    )
    if match is None:
        raise ReviewError(f"{case_id} has no finding {code} at {path}")
    if match.severity is Severity.ERROR:
        raise ReviewError(
            f"{code} is an error and cannot be accepted; fix the draft instead"
        )

    at = _now()
    finding = AcceptedFinding(
        code=code, path=path, justification=justification.strip(), by=by, at=at
    )
    updated = replace(case, accepted_findings=(*case.accepted_findings, finding))
    project.test_cases[project.test_cases.index(case)] = updated
    project.history.append(
        ReviewEvent(
            action=ReviewAction.QUESTION_RESOLVED,
            case_id=case_id,
            revision=case.revision,
            at=at,
            by=by,
            note=f"accepted {code} at {path}: {justification.strip()}",
            categories=(code,),
        )
    )
    return updated


def revoke_finding(
    project: Project, case_id: str, code: str, path: str, *, by: str = DEFAULT_REVIEWER
) -> TestCase:
    """Take an acceptance back; the finding blocks approval again."""
    case = _require_case(project, case_id)
    remaining = tuple(
        f for f in case.accepted_findings if (f.code, f.path) != (code, path)
    )
    if len(remaining) == len(case.accepted_findings):
        raise ReviewError(f"{case_id} has no accepted finding {code} at {path}")
    updated = replace(case, accepted_findings=remaining)
    project.test_cases[project.test_cases.index(case)] = updated
    project.history.append(
        ReviewEvent(
            action=ReviewAction.REOPENED,
            case_id=case_id,
            revision=case.revision,
            at=_now(),
            by=by,
            note=f"acceptance of {code} at {path} withdrawn",
        )
    )
    return updated


# ---------------------------------------------------------------- decision ---
def approval_report(project: Project, case_id: str) -> tuple[bool, ValidationReport]:
    """Re-run the deterministic validation for this exact revision."""
    case = _require_case(project, case_id)
    return may_approve(
        case, project.requirements, open_questions=case.unresolved_questions
    )


def approve_case(
    project: Project,
    case_id: str,
    *,
    by: str = DEFAULT_REVIEWER,
    note: str | None = None,
) -> TestCase:
    """Approve a draft - a deliberate decision, checked once more."""
    case = _require_case(project, case_id)
    if case.needs_recheck:
        raise ApprovalBlocked(
            f"{case_id} must be reviewed again: its requirements changed",
            ValidationReport(),
        )
    allowed, report = approval_report(project, case_id)
    if not allowed:
        raise ApprovalBlocked(
            f"{case_id} cannot be approved: "
            + "; ".join(str(issue) for issue in report.issues[:5]),
            report,
        )
    return _decide(
        project,
        case,
        ReviewStatus.APPROVED,
        ReviewAction.APPROVED,
        by=by,
        note=note,
    )


def reject_case(
    project: Project,
    case_id: str,
    *,
    by: str = DEFAULT_REVIEWER,
    note: str | None = None,
    categories: Sequence[str] = (),
) -> TestCase:
    """Reject a draft. A reason is required so the decision stays readable."""
    if not (note or "").strip():
        raise ReviewError("a rejection needs a reason")
    case = _require_case(project, case_id)
    return _decide(
        project,
        case,
        ReviewStatus.REJECTED,
        ReviewAction.REJECTED,
        by=by,
        note=note,
        categories=categories,
    )


def request_clarification(
    project: Project,
    case_id: str,
    *,
    by: str = DEFAULT_REVIEWER,
    note: str | None = None,
) -> TestCase:
    case = _require_case(project, case_id)
    return _decide(
        project,
        case,
        ReviewStatus.NEEDS_CLARIFICATION,
        ReviewAction.CLARIFICATION_REQUESTED,
        by=by,
        note=note,
    )


def reopen_case(
    project: Project, case_id: str, *, by: str = DEFAULT_REVIEWER, note: str | None = None
) -> TestCase:
    """Take a decision back; the draft returns to ``draft``."""
    case = _require_case(project, case_id)
    return _decide(
        project, case, ReviewStatus.DRAFT, ReviewAction.REOPENED, by=by, note=note
    )


def _decide(
    project: Project,
    case: TestCase,
    status: ReviewStatus,
    action: ReviewAction,
    *,
    by: str,
    note: str | None,
    categories: Sequence[str] = (),
) -> TestCase:
    updated = replace(case, review_status=status, review_note=note)
    project.test_cases[project.test_cases.index(case)] = updated
    project.history.append(
        ReviewEvent(
            action=action,
            case_id=case.case_id,
            revision=case.revision,
            at=_now(),
            by=by,
            note=note,
            status_before=case.review_status,
            status_after=status,
            categories=tuple(categories),
        )
    )
    return updated


# ----------------------------------------------------------- source change ---
def apply_requirement_changes(
    project: Project, requirements: Sequence[Requirement]
) -> list[TestCase]:
    """Take in a re-imported requirement set and flag the affected drafts.

    A draft whose requirement text changed, or whose requirement disappeared,
    is marked for a fresh review and loses its approval. Nothing is deleted.
    """
    incoming = {r.requirement_id: r for r in requirements}
    previous = {r.requirement_id: r for r in project.requirements}
    changed = {
        rid
        for rid, requirement in incoming.items()
        if rid in previous and previous[rid].text != requirement.text
    }
    removed = set(previous) - set(incoming)
    affected_ids = changed | removed
    if not affected_ids:
        project.requirements = list(requirements)
        return []

    at = _now()
    touched: list[TestCase] = []
    for index, case in enumerate(project.test_cases):
        if not affected_ids.intersection(case.requirement_ids):
            continue
        reason = (
            "requirement removed"
            if removed.intersection(case.requirement_ids)
            else "requirement text changed"
        )
        updated = replace(
            case,
            needs_recheck=True,
            review_status=(
                ReviewStatus.DRAFT
                if case.review_status is ReviewStatus.APPROVED
                else case.review_status
            ),
        )
        project.test_cases[index] = updated
        touched.append(updated)
        project.history.append(
            ReviewEvent(
                action=ReviewAction.SOURCE_CHANGED,
                case_id=case.case_id,
                revision=case.revision,
                at=at,
                note=reason,
                status_before=case.review_status,
                status_after=updated.review_status,
            )
        )
    project.requirements = list(requirements)
    return touched


# ------------------------------------------------------------------ report ---
def validation_overview(project: Project) -> dict[str, ValidationReport]:
    """Current findings per draft, recomputed from the stored data."""
    return {
        case.case_id: validate_test_case(case, project.requirements)
        for case in project.test_cases
    }


def _require_case(project: Project, case_id: str) -> TestCase:
    case = project.case(case_id)
    if case is None:
        raise ReviewError(f"unknown test case {case_id!r}")
    return case


def unresolved_questions(project: Project) -> Iterable[tuple[str, OpenQuestion]]:
    for case in project.test_cases:
        for question in case.unresolved_questions:
            yield case.case_id, question
